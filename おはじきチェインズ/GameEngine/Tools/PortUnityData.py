# A deliberately restricted Unity text-asset reader. Reject anything outside the
# field/sequence/inline scalar syntax used by these three versioned source assets.
def scalar(s):
    if not s:return None
    if s.startswith('"'):return json.loads(s)
    if s.startswith('{'):
        return {k.strip():scalar(v.strip()) for k,v in (p.split(':',1) for p in s[1:-1].split(','))}
    if s=='[]':return []
    if re.fullmatch(r'-?\d+',s):return int(s) if len(s)<14 else s
    if re.fullmatch(r'-?\d+\.\d+(?:[eE][+-]?\d+)?',s):return float(s)
    return s
def yaml_asset(path):
    lines=[(len(l)-len(l.lstrip()),l.strip()) for l in path.read_text(encoding='utf-8-sig').splitlines()[4:] if l.strip()]
    def block(pos,indent,array=False):
        out=[] if array else {}
        while pos<len(lines):
            depth,s=lines[pos]
            if depth<indent or depth==indent and s.startswith('- ')!=array:break
            if depth!=indent:raise ValueError((path,pos,s))
            if array:
                if s[2:].startswith('{'):
                    out.append(scalar(s[2:]));pos+=1;continue
                if ':' not in s[2:]:out.append(scalar(s[2:]));pos+=1;continue
                # Merge a sequence item's first field into its following mapping.
                key,val=s[2:].split(':',1);item={key:scalar(val.strip())};pos+=1
                if pos<len(lines) and lines[pos][0]>indent:
                    rest,pos=block(pos,lines[pos][0]);item.update(rest)
                out.append(item)
            else:
                key,val=s.split(':',1);pos+=1;val=val.strip()
                if not val and pos<len(lines) and (lines[pos][0]>indent or lines[pos][0]==indent and lines[pos][1].startswith('- ')):
                    item,pos=block(pos,lines[pos][0],lines[pos][1].startswith('- '));out[key]=item
                else:out[key]=scalar(val)
        return out,pos
    return block(0,2)[0]

data=root/'Assets/Data';data.mkdir(parents=True,exist_ok=True)
for asset in ['HubConfig','BattleTuning','ShopConfig']:
    path=source/'Assets/Ohajiki'/(asset+'.asset')
    values=yaml_asset(path)
    values={k:v for k,v in values.items() if not k.startswith('m_') and k not in ['catalog','quests','banners','shop','playerDeck','enemyDeck']}
    for key in ['effectThresholds','contactCelebrationThresholds']:
        if key in values and isinstance(values[key],str):
            raw=bytes.fromhex(values[key]);values[key]=list(struct.unpack('<'+'i'*(len(raw)//4),raw))
    (data/(asset+'.json')).write_text(json.dumps(values,ensure_ascii=False,indent=2),encoding='utf-8')
    manifest[str(path.relative_to(source))]=hashlib.sha256(path.read_bytes()).hexdigest()

assets={}
for path in (source/'Assets/Ohajiki').rglob('*.png'):
    relative=Path('Assets/Imported')/path.relative_to(source/'Assets/Ohajiki')
    target=root/relative;target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(path,target)
    record={'Path':relative.as_posix()}
    assets[path.relative_to(source).as_posix()]=record
    meta=path.with_suffix(path.suffix+'.meta')
    if meta.exists():
        match=re.search(r'^guid: (\w+)',meta.read_text(encoding='utf-8'),re.M)
        if match:assets[match[1]]=record
(data/'Textures.json').write_text(json.dumps(assets,ensure_ascii=False,indent=2),encoding='utf-8')
shutil.copy2(root.parent/'MasterData.xlsx',data/'MasterData.xlsx')
